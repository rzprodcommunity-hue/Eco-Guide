import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

class LocaleProvider extends ChangeNotifier {
  static const String _localeKey = 'settings_locale';

  Locale _locale = const Locale('fr');

  LocaleProvider() {
    _loadLocale();
  }

  Locale get locale => _locale;

  String get languageCode => _locale.languageCode;

  String get languageLabel {
    switch (_locale.languageCode) {
      case 'en':
        return 'English (EN)';
      case 'ar':
        return 'العربية (AR)';
      case 'fr':
      default:
        return 'Français (FR)';
    }
  }

  Future<void> _loadLocale() async {
    final prefs = await SharedPreferences.getInstance();
    final code = prefs.getString(_localeKey) ?? 'fr';
    _locale = Locale(code);
    notifyListeners();
  }

  Future<void> setLocale(String code) async {
    if (code != 'fr' && code != 'en' && code != 'ar') return;
    _locale = Locale(code);
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_localeKey, code);
    notifyListeners();
  }

  /// Translate a key using the current locale.
  String t(String key) {
    final map = _strings[_locale.languageCode] ?? _strings['fr']!;
    return map[key] ?? _strings['fr']![key] ?? key;
  }
}

